package keiyoushi.runtime.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * `keiyoushi.runtime.host.BuildModules`: the modules of one host variant, with their API levels and
 * `Entry` objects, and the licenses under `assets/licenses/`. Java, because the launcher screen
 * reads it in the runtime's own process, where no app provides the Kotlin stdlib.
 */
@CacheableTask
abstract class GenerateRegistryTask : DefaultTask() {
    /** `name:api:minApi` */
    @get:Input
    abstract val modules: ListProperty<String>

    /** One license per bundled library, `assets/licenses/<library>.txt` */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NAME_ONLY)
    abstract val licenses: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val modules = modules.get().map(ModuleSpec::decode).sortedBy { it.name }
        val licenses = licenses.files.map { it.name }.sorted()
        val root = outputDir.get().asFile
        root.deleteRecursively()
        val file = root.resolve("keiyoushi/runtime/host/BuildModules.java")
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by build-logic from modules/*. Do not edit.
            |package keiyoushi.runtime.host;
            |
            |/** The runtime modules in this build, in name order */
            |public final class BuildModules {
            |    private BuildModules() {}
            |
            |    public static final String[] NAMES = {${modules.joinToString { "\"${it.name}\"" }}};
            |
            |    /** The API level each module serves */
            |    public static final int[] APIS = {${modules.joinToString { "${it.api}" }}};
            |
            |    /** The lowest API level each module still serves */
            |    public static final int[] MIN_APIS = {${modules.joinToString { "${it.minApi}" }}};
            |
            |    /** Bundled libraries, and their license files as asset paths */
            |    public static final String[] LICENSE_NAMES = {${licenses.joinToString { "\"${it.substringBeforeLast('.')}\"" }}};
            |    public static final String[] LICENSE_PATHS = {${licenses.joinToString { "\"licenses/$it\"" }}};
            |
            |    /** Each module's {@code keiyoushi.runtime.<name>.Entry}. This initialises them: only the extension's factory calls it. */
            |    public static Object[] entries() {
            |        return new Object[] {${modules.joinToString { "keiyoushi.runtime.${it.name}.Entry.INSTANCE" }}};
            |    }
            |}
            |
            """.trimMargin(),
        )
    }
}
